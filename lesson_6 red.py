# break (Экстренный выход)Представь, что ты ищешь нужную клюкву в коробке.
# Как только ты её нашел, перебирать коробку дальше нет смысла.
# Ты прекращаешь поиск и выходишь из магазина.
# Пример: Цикл перебирает числа от 1 до 10. Если встречается число 5, break полностью останавливает цикл.
#
# continue (Пропуск шага)Ты моешь тарелки. Тебе попадается чистая тарелка.
# Ты не перестаешь мыть посуду в принципе,
# ты просто откладываешь эту тарелку и сразу переходишь к следующей.
# Пример: Цикл печатает числа, но если число четное, continue пропускает его печать и переходит к следующему числу
#
# .else в цикле (Успешное завершение)Это блок, который выполняется, только если цикл завершился сам (дойдя до конца),
# и не был прерван командой break. Представь, что ты обыскал всю комнату в поисках ключей.
# Если ты их нашел (break), то объявление «Я не нашёл ключи!» делать не будешь.
# А вот если ты честно осмотрел всю комнату и ключей не оказалось — сработает else.

