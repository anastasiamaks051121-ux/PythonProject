#Переменная - именованная область памяти, предназначенная для хранения значения.
#сам язык программирования ищет свободные ячейки памяти в компьютере,
# которые тот готов выделить программисту для его нужд.
# Программист придумывает осмысленное имя для этой ячейки памяти, например, name,
# и язык программирования связывает придуманное программистом имя с номером ячейки памяти.
#Теперь программисту вместо адреса, скажем, 048907B0, нужно написать всего
# лишь имя переменной name для обращения к ячейке памяти.
# Вот так работает механизм переменных, и вот почему переменная называется именованной областью памяти.

#Переменную можно представить в виде коробочки, в которой вы можете хранить
# одно значение в один момент времени. Из этой коробки можно убирать значение и класть туда другое.
# Но зная имя коробки, вы всегда можете посмотреть, что в ней лежит в данный момент.
# Переменная создается в момент первого присваивания к ней значения.
#Вы можете сколько угодно раз менять значение переменной,
# записывая в нее новое значение. Но создание переменной происходит только в момент первого присваивания значения, во все остальные разы вы лишь изменяете значение переменной.
#Переменная в python не хранит само значение, она хранит ссылку (адрес) на объект.
#Переменная в python в начале может хранить ссылку на число, затем мы можем присвоить ей ссылку на строку,
# и это не вызовет ошибку, как в некоторых других языках программирования. Языки программирования, в которых можно
# в одну переменную сохранять объекты с различным типом данных, называют языками с динамической типизацией.
# Противоположные языки(например паскаль), где за переменной привязан тип данных, называют языками со статической типизацией.
